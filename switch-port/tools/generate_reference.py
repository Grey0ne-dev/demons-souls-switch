#!/usr/bin/env python3
"""Generate metadata and hashes only from the verified BLUS30443 1.00 ELF."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
EXPECTED_SHA256 = "90eaa5e9e48b4874292badc311ccea253e6a622ff188bfbdbe76e6f6821269d8"


def hash_memory(file_bytes, memory_size):
    digest = hashlib.sha256(file_bytes)
    remaining = memory_size - len(file_bytes)
    zeros = bytes(65536)
    while remaining:
        count = min(remaining, len(zeros))
        digest.update(zeros[:count])
        remaining -= count
    return digest.hexdigest()


def byte_array(digest):
    return "{ " + ", ".join("0x" + digest[i:i + 2] for i in range(0, len(digest), 2)) + " }"


def generate(source):
    data = source.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError("Input does not match the verified US v1.00 EBOOT.ELF SHA-256")
    fields = struct.unpack_from(">16sHHIQQQIHHHHHH", data)
    if fields[0][:7] != b"\x7fELF\x02\x02\x01" or fields[1:4] != (2, 21, 1):
        raise ValueError("Expected a big-endian ELF64 PPC64 executable")
    entry, phoff, phsize, phcount = fields[4], fields[5], fields[9], fields[10]
    segments = []
    tls = None
    for i in range(phcount):
        kind, flags, offset, vaddr, _paddr, filesz, memsz, alignment = struct.unpack_from(
            ">II6Q", data, phoff + i * phsize)
        if kind == 1 and memsz:
            raw = data[offset:offset + filesz]
            if len(raw) != filesz or filesz > memsz:
                raise ValueError("Invalid PT_LOAD extent")
            segments.append({"program_header_index": i, "guest_address": vaddr,
                             "flags": flags, "file_offset": offset, "file_size": filesz,
                             "memory_size": memsz, "alignment": alignment,
                             "file_sha256": hashlib.sha256(raw).hexdigest(),
                             "memory_sha256": hash_memory(raw, memsz)})
        elif kind == 7:
            tls = {"guest_address": vaddr, "file_size": filesz, "memory_size": memsz,
                   "file_offset": offset, "alignment": alignment}
    def read_guest(address, size):
        for segment in segments:
            start = segment["guest_address"]
            delta = address - start
            if 0 <= delta and size <= segment["file_size"] - delta:
                offset = segment["file_offset"] + delta
                return data[offset:offset + size]
        raise ValueError("Entry descriptor not backed by file bytes")
    code, toc = struct.unpack(">II", read_guest(entry, 8))
    return {"title_id": "BLUS30443", "app_version": "01.00", "file_size": len(data),
            "file_sha256": digest, "entry_descriptor": entry, "entry_code": code,
            "toc": toc, "allocated_bytes": sum(s["memory_size"] for s in segments),
            "segments": segments, "tls": tls,
            "scope": "Hashes and metadata only; no game code or asset bytes."}


def header(reference):
    lines = ["/* Generated by tools/generate_reference.py. Metadata and hashes only. */",
             "#ifndef DS_REFERENCE_H", "#define DS_REFERENCE_H", "",
             "#include <stddef.h>", "#include <stdint.h>", "",
             '#define DS_REF_TITLE_ID "BLUS30443"', '#define DS_REF_APP_VERSION "01.00"',
             f'#define DS_REF_FILE_SIZE UINT64_C({reference["file_size"]})',
             f'#define DS_REF_ALLOCATED_BYTES UINT64_C({reference["allocated_bytes"]})',
             f'#define DS_REF_ENTRY_DESCRIPTOR UINT32_C(0x{reference["entry_descriptor"]:08x})',
             f'#define DS_REF_ENTRY_CODE UINT32_C(0x{reference["entry_code"]:08x})',
             f'#define DS_REF_TOC UINT32_C(0x{reference["toc"]:08x})',
             f'#define DS_REF_SEGMENT_COUNT {len(reference["segments"])}u',
             f'#define DS_REF_TLS_ADDRESS UINT32_C(0x{reference["tls"]["guest_address"]:08x})',
             f'#define DS_REF_TLS_FILE_SIZE {reference["tls"]["file_size"]}u',
             f'#define DS_REF_TLS_MEMORY_SIZE {reference["tls"]["memory_size"]}u', "",
             "typedef struct {", "    uint32_t guest_address;", "    uint32_t flags;",
             "    uint64_t file_offset;", "    uint64_t file_size;", "    uint64_t memory_size;",
             "    unsigned char file_sha256[32];", "    unsigned char memory_sha256[32];",
             "} DsReferenceSegment;", "",
             "static const unsigned char DS_REF_FILE_SHA256[32] = " + byte_array(reference["file_sha256"]) + ";", "",
             "static const DsReferenceSegment DS_REF_SEGMENTS[DS_REF_SEGMENT_COUNT] = {"]
    for segment in reference["segments"]:
        lines.extend(["    {", f'        UINT32_C(0x{segment["guest_address"]:08x}), UINT32_C(0x{segment["flags"]:08x}),',
                      f'        UINT64_C({segment["file_offset"]}), UINT64_C({segment["file_size"]}), UINT64_C({segment["memory_size"]}),',
                      "        " + byte_array(segment["file_sha256"]) + ",",
                      "        " + byte_array(segment["memory_sha256"]), "    },"])
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "upstream/DemonsSoulsRecomp/work/game/EBOOT.ELF")
    parser.add_argument("--json", type=Path, default=ROOT / "switch-port/reference.json")
    parser.add_argument("--header", type=Path, default=ROOT / "switch-port/include/ds_reference.h")
    args = parser.parse_args()
    reference = generate(args.input)
    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(reference, indent=2) + "\n")
    args.header.write_text(header(reference))
    print(f'Verified {reference["file_sha256"]}; {len(reference["segments"])} load segments, {reference["allocated_bytes"]} backed bytes')


if __name__ == "__main__":
    main()
